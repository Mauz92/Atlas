#!/usr/bin/env python3
"""Generate apps/web/nginx.tls.conf from nginx.conf (one source of truth for the locations).

    python3 apps/web/make-nginx-tls.py          # rewrite nginx.tls.conf
    python3 apps/web/make-nginx-tls.py --check  # exit 1 when nginx.tls.conf is stale (used by a unit test)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TLS_BLOCK = """    listen 443 ssl;
    server_name _;

    # TLS for a tailnet-only name (galaxia-atlas.duckdns.org): the certificate and key come from the
    # host's ACME client (docs/DEPLOYMENT.md section 8.3), mounted read-only at /etc/nginx/certs.
    ssl_certificate     /etc/nginx/certs/fullchain.pem;
    ssl_certificate_key /etc/nginx/certs/privkey.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_session_cache   shared:SSL:2m;
    ssl_session_timeout 1h;
    ssl_session_tickets off;
    add_header Strict-Transport-Security "max-age=15552000" always;"""
HEADER = (
    "# GENERATED by apps/web/make-nginx-tls.py from nginx.conf: do not edit by hand.\n"
    "# Used only with deploy/docker-compose.tls.yml (docs/DEPLOYMENT.md section 8.3): the plain-HTTP server on\n"
    "# port 80 is kept (loopback publish, tailscale serve) and a TLS server on 443 is added.\n"
)


def build() -> str:
    src = (HERE / "nginx.conf").read_text()
    match = re.search(r"\nserver \{.*\n\}\n", src, re.S)
    assert match, "no server block in nginx.conf"
    server = match.group(0)
    tls = server.replace("    listen 80;\n    server_name _;", TLS_BLOCK, 1)
    # add_header in a location replaces the server-level ones, so HSTS is repeated where headers are set.
    tls = tls.replace(
        '        add_header X-Content-Type-Options "nosniff" always;',
        '        add_header Strict-Transport-Security "max-age=15552000" always;\n'
        '        add_header X-Content-Type-Options "nosniff" always;',
        1,
    )
    return HEADER + src[: match.start() + 1] + server + "\n" + tls


if __name__ == "__main__":
    out = HERE / "nginx.tls.conf"
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if out.exists() and out.read_text() == text else 1)
    out.write_text(text)
